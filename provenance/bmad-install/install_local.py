"""Reproduce the local, explicitly selected BMAD installation (no workflow execution)."""
from pathlib import Path
import shutil, hashlib, json, csv, subprocess, tomllib

root = Path(__file__).resolve().parents[2]
source = Path('D:/shinshi')
record = Path(__file__).parent
names = sorted(p.name for p in (source/'.agents/skills').iterdir() if p.is_dir() and p.name.startswith(('gds-', 'bmad-')))
assert not (root/'_bmad').exists(), 'Refuse overwrite'
hashes = []
def copy(src, dst):
    if src.is_dir():
        for f in src.rglob('*'):
            if f.is_file() and '__pycache__' not in f.parts:
                copy(f, dst/f.relative_to(src))
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src,dst)
        hashes.append({'source':str(src.relative_to(source)).replace('\\','/'), 'destination':str(dst.relative_to(root)).replace('\\','/'), 'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest()})
for name in names:
    for base in ['.agents/skills','.claude/skills']:
        assert not (root/base/name).exists(), name
        copy(source/'.agents/skills'/name,root/base/name)
for folder in ['scripts','core','gds','render']:
    copy(source/'_bmad'/folder,root/'_bmad'/folder)
for name in ['bmad-help.csv','skill-manifest.csv']:
    copy(source/'_bmad/_config'/name,root/'_bmad/_config'/name)
def write(path,text):
    p=root/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text,encoding='utf-8')
config=(source/'_bmad/config.toml').read_text(encoding='utf-8').replace('"shinshi"','"DIGETHER"').replace('"unity"','"unreal"').replace('_bmad-output/planning-artifacts','_bmad-output/planning-drafts')
config=config.replace('[core]','[core]\nuser_name = "Project contributor"\ncommunication_language = "Korean"')
write('_bmad/config.toml',config)
for module in ['core','gds']:
    data=(source/f'_bmad/{module}/config.yaml').read_text(encoding='utf-8')
    data=data.replace('shinshi','DIGETHER').replace('Minsung','Project contributor').replace('primary_platform: unity','primary_platform: unreal').replace('_bmad-output/planning-artifacts','_bmad-output/planning-drafts')
    data=data.replace('# Generated by BMAD installer','# Generated for DIGETHER from local installed module schema').replace('# Date: 2026-09-30T11:47:37.188Z','# Prepared: 2026-10-23').replace('# Date: 2026-09-30T11:47:37.189Z','# Prepared: 2026-10-23')
    write(f'_bmad/{module}/config.yaml',data)
write('_bmad/.gitignore','config.user.toml\n**/*.user.toml\n**/config.user.yaml\n**/__pycache__/\nrender/*\n!render/.gitignore\n')
facts=['file:{project-root}/AGENTS.md','file:{project-root}/docs/project/PROJECT_PROFILE.md','file:{project-root}/docs/project/DOCUMENTATION.md','Engine is Unreal Engine 5.8.2; do not change versions automatically.','Notion is the authoritative planning source. Before migration consult docs/project/notion/GAME_DESIGN.md. BMAD planning output is an unapproved local draft, never an automatic replacement for Notion or project decisions.','Project files are managed with GitHub. Installing skills grants no permission to invoke agents, execute workflows, commit, push, publish, or transmit externally; follow the current task authorization.']
for name in names:
    custom=root/'.agents/skills'/name/'customize.toml'
    if custom.exists():
        cfg=tomllib.loads(custom.read_text(encoding='utf-8'))
        block='agent' if 'agent' in cfg else 'workflow'
        if block in cfg:
            write(f'_bmad/custom/{name}.toml',f'[{block}]\npersistent_facts = '+json.dumps(facts,ensure_ascii=False)+'\n')
    # Brief project adapter is present even for core skills without customization.
    for base in ['.agents/skills','.claude/skills']:
        p=root/base/name/'SKILL.md';text=p.read_text(encoding='utf-8');end=text.find('\n---',4)+4
        text=text[:end]+'\n\n## DIGETHER project integration\n\nRead `{project-root}/_bmad/PROJECT_INTEGRATION.md` before activation. Project instructions and the user\'s scope govern this imported workflow.\n'+text[end:]
        p.write_text(text,encoding='utf-8')
# Repair upstream catalog paths to the canonical project source copies.
p=root/'_bmad/_config/skill-manifest.csv'
rows=list(csv.DictReader(p.open(encoding='utf-8')))
for row in rows: row['path']='.agents/skills/'+row['name']+'/SKILL.md'
with p.open('w',encoding='utf-8',newline='') as f:
    w=csv.DictWriter(f,fieldnames=rows[0].keys());w.writeheader();w.writerows(rows)
write('_bmad/_config/manifest.yaml','installation:\n  version: 6.12.0\n  method: curated-local-copy\n  prepared: 2026-10-23\nmodules:\n  - name: core\n    version: 6.12.0\n    repoUrl: https://github.com/bmad-code-org/BMAD-METHOD\n  - name: gds\n    version: v0.7.2\n    repoUrl: https://github.com/bmad-code-org/bmad-module-game-dev-studio.git\n    sha: 2486f5f5f3b8870baa6cee4615a870c0330f441c\nides:\n  - codex\n  - claude-code\n')
write('_bmad/PROJECT_INTEGRATION.md','''# DIGETHER BMAD 적용 경계

Unreal Engine **5.8.2**, 한국어, 프로젝트 파일 관리 **GitHub**를 따른다. 플랫폼 선택은 `unreal`이다. 사용자 이름은 신원을 추측하지 않는 `Project contributor` 기본값이다.

기획 운영 원본은 **Notion**이며 이관 전 기준은 `docs/project/notion/GAME_DESIGN.md`다. BMAD의 “GDD canonical source”는 이 프로젝트에서 승인된 Notion 기획과 동기화된 작업용 사본을 뜻한다. 새 출력은 `_bmad-output/planning-drafts/`의 미승인 초안으로 분류하며 기존 기획을 자동 대체하지 않는다. 기술·실행 산출물은 `_bmad-output/implementation-artifacts/`로 분리한다. 기획 동기화·외부 게시·커밋·푸시는 현재 사용자 요청에 따른다.

사용 전 `AGENTS.md`, `docs/project/PROJECT_PROFILE.md`, `docs/project/DOCUMENTATION.md`, `docs/ai/EXECUTION_POLICY.md`를 확인한다. 스킬의 에이전트·자동화·테스트 안내는 사용 가능한 런타임과 승인 범위에서만 적용한다. 설치 자체는 실행, 위임, 업로드 또는 외부 전송 승인이 아니다. 현재 엔진 프로젝트·환경의 부재는 성공으로 보고하지 않는다. 네트워크와 게임 규칙을 추정해 확정하지 않는다.

관리 원본이자 Codex 발견 경로는 `.agents/skills/`, Claude Code 동기화 사본은 `.claude/skills/`다. 두 경로는 지원 파일과 상대 링크를 포함해 동일하게 유지한다. 공용 런타임·카탈로그는 `_bmad/`다. `uv`와 Python 3.11 이상을 사용한다. 사용자별 설정은 복사하지 않았다.

출처·라이선스·파일 해시는 `provenance/bmad-install/`에 보존한다. 이 설치는 로컬 고정 설치본의 재사용이며 upstream 전체와의 동일성을 주장하지 않는다.
''')
for h in hashes:
    h['installed_sha256']=hashlib.sha256((root/h['destination']).read_bytes()).hexdigest()
(record/'file-hashes.json').write_text(json.dumps(hashes,ensure_ascii=False,indent=2),encoding='utf-8')
(record/'skills.json').write_text(json.dumps(names,indent=2),encoding='utf-8')
print(json.dumps({'skills':len(names),'gds':len([n for n in names if n.startswith('gds-')]),'core':len([n for n in names if n.startswith('bmad-')]),'copied_files':len(hashes)}))
