"""플레이어 몸을 캐릭터 모델 v1.5(SK_Ch_v15_Body)로 바꾼다(에디터 Python).

먼저 retarget_ch_v15.py를 실행해 메시·리타게터·V15 애니메이션이 있어야 한다.
실행(에디터를 닫고):
  UnrealEditor-Cmd.exe <프로젝트>.uproject -run=pythonscript -script=<이 파일> -unattended -nosplash -nop4

하는 일:
1. 손 소켓 hand_r_socket을 v15 메시에 만든다. 드워프 소켓이 Idle 첫 프레임에서 놓이는 방향·손 기준 위치(키 비율 보정)를 그대로 옮긴다.
2. 현재 쓰는 ABP_UnarmedDG(부모 DigetherPlayerAnimInstance, Slot 등 수정 포함)를 드워프→v15로 리타겟해 ABP_UnarmedV15로 둔다.
   딸려 복제된 애니메이션(드워프를 한 번 더 거친 것)은 마네킹에서 바로 리타겟한 *V15 애니메이션으로 참조를 합친다.
3. 삽 공격 몽타주 AM_Shovel_Attack이 드워프 스켈레톤이면 노티파이가 기본값인지 알려 준다.
   기본값이면 파일을 지우고 create_shovel_attack_assets.py를 실행해 v15 스켈레톤으로 다시 만든다.
커맨드렛에서는 에셋 삭제가 디스크에 반영되지 않는다. 그래서 ABP 리타겟에 딸려 복제된 임시 애니메이션(Anims/_ABPTemp)은
참조를 합친 뒤에도 파일이 남는다. ABP 참조 확인 로그에 _TMP15가 없으면 그 폴더를 지운다.
4. BP_DigatherPlayer의 몸 메시·애님 클래스·뷰포트용 스케일/위치를 v15로 바꾼다.
"""

import unreal

V15 = "/Game/Characters/DwarfV15"
V15_MESH = f"{V15}/SK_Ch_v15_Body"
V15_ANIMS = f"{V15}/Anims"
V15_RIG = f"{V15}/Retarget/IK_Ch_v15_Body"
DWARF_TO_V15 = f"{V15}/Retarget/RTG_Dwarf_To_Ch_v15"
TMP_DIR = f"{V15}/Anims/_ABPTemp"
TMP_SUFFIX = "_TMP15"

DWARF_MESH = "/Game/Characters/Dwarf/SK_Ch_Dwarf_Miner_UE3"
DWARF_RIG = "/Game/Characters/Dwarf/Retarget/IK_AutoGeneratedTarget"
DWARF_ABP = "/Game/Characters/Dwarf/Anims/ABP_UnarmedDG"
DWARF_IDLE = "/Game/Characters/Dwarf/Anims/MM_IdleDG"
V15_IDLE = f"{V15_ANIMS}/MM_IdleV15"
V15_ABP = f"{V15_ANIMS}/ABP_UnarmedV15"

SOCKET = "hand_r_socket"
SHOVEL_MONTAGE = "/Game/Game/Weapon/Shovel/AM_Shovel_Attack"
DEFAULT_HIT_START_RATIO = 0.30
DEFAULT_HIT_LENGTH_RATIO = 0.20
PLAYER_BP = "/Game/Game/Player/BP_DigatherPlayer"
PLAYER_HEIGHT_CM = 165.0

EAL = unreal.EditorAssetLibrary
TOOLS = unreal.AssetToolsHelpers.get_asset_tools()
ANIMLIB = unreal.AnimationLibrary
SIDE = unreal.RetargetSourceOrTarget


def log(msg: str) -> None:
    unreal.log(f"[swap_player_to_ch_v15] {msg}")


def load(path: str):
    asset = EAL.load_asset(path)
    if asset is None:
        raise RuntimeError(f"에셋을 찾을 수 없다: {path}")
    return asset


def bone_cs(anim, bone: str) -> unreal.Transform:
    """애니메이션 첫 프레임에서 본의 컴포넌트 공간 트랜스폼."""
    path = list(ANIMLIB.find_bone_path_to_root(anim, bone))
    if path and str(path[0]) == bone:
        path.reverse()
    t = unreal.Transform()
    for name in path:
        local = ANIMLIB.get_bone_pose_for_time(anim, name, 0.0, False)
        t = unreal.MathLibrary.compose_transforms(local, t)
    return t


def mesh_height(mesh) -> float:
    return mesh.get_imported_bounds().box_extent.z * 2.0


def make_socket() -> None:
    v15 = load(V15_MESH)
    if v15.find_socket(SOCKET):
        log(f"소켓 있음, 건너뜀: {SOCKET}")
        return
    dwarf = load(DWARF_MESH)
    src = dwarf.find_socket(SOCKET)
    if src is None:
        raise RuntimeError(f"드워프 메시에 {SOCKET}이 없다")
    bone = str(src.get_editor_property("bone_name"))
    d_hand = bone_cs(load(DWARF_IDLE), bone)
    v_hand = bone_cs(load(V15_IDLE), "hand_r")
    s_local = unreal.Transform(src.get_editor_property("relative_location"),
                               src.get_editor_property("relative_rotation"),
                               src.get_editor_property("relative_scale"))
    d_sock = unreal.MathLibrary.compose_transforms(s_local, d_hand)
    ratio = mesh_height(v15) / mesh_height(dwarf)
    offset = (d_sock.translation - d_hand.translation) * ratio
    want = unreal.Transform(v_hand.translation + offset, d_sock.rotation.rotator(), unreal.Vector(1, 1, 1))
    local = unreal.MathLibrary.compose_transforms(want, v_hand.inverse())
    # SocketName은 Python에서 직접 쓸 수 없어 이름 없이 추가한 뒤 RenameSocket으로 이름을 붙인다
    sock = unreal.SkeletalMeshSocket(outer=v15)
    sock.set_socket_parent(v15, "hand_r")
    sock.set_editor_property("relative_location", local.translation)
    sock.set_editor_property("relative_rotation", local.rotation.rotator())
    v15.add_socket(sock, False)
    if not unreal.SkeletalMeshEditorSubsystem.rename_socket(v15, sock.get_editor_property("socket_name"), SOCKET):
        raise RuntimeError(f"소켓 이름 지정 실패: {SOCKET}")
    if v15.find_socket(SOCKET) is None:
        raise RuntimeError(f"소켓 생성 확인 실패: {SOCKET}")
    EAL.save_loaded_asset(v15, only_if_is_dirty=False)
    log(f"소켓 생성 {SOCKET}@hand_r loc={local.translation} rot={local.rotation.rotator()} "
        f"(드워프 손→소켓 {offset.length() / ratio:.1f}cm, 키 비율 {ratio:.3f})")


def make_dwarf_retargeter() -> unreal.IKRetargeter:
    if EAL.does_asset_exist(DWARF_TO_V15):
        return load(DWARF_TO_V15)
    src_rig, tgt_rig = load(DWARF_RIG), load(V15_RIG)
    folder, name = DWARF_TO_V15.rsplit("/", 1)
    rtg = TOOLS.create_asset(name, folder, unreal.IKRetargeter, unreal.IKRetargetFactory())
    ctrl = unreal.IKRetargeterController.get_controller(rtg)
    ctrl.set_ik_rig(SIDE.SOURCE, src_rig)
    ctrl.set_ik_rig(SIDE.TARGET, tgt_rig)
    ctrl.set_preview_mesh(SIDE.SOURCE, load(DWARF_MESH))
    ctrl.set_preview_mesh(SIDE.TARGET, load(V15_MESH))
    if ctrl.get_num_retarget_ops() == 0:
        ctrl.add_default_ops()
    ctrl.assign_ik_rig_to_all_ops(SIDE.SOURCE, src_rig)
    ctrl.assign_ik_rig_to_all_ops(SIDE.TARGET, tgt_rig)
    ctrl.auto_map_chains(unreal.AutoMapChainType.FUZZY, True)
    ctrl.auto_align_all_bones(SIDE.TARGET)
    EAL.save_loaded_asset(rtg, only_if_is_dirty=False)
    log(f"리타게터 생성: {DWARF_TO_V15}")
    return rtg


def v15_name_for(dup_name: str) -> str:
    base = dup_name[: -len(TMP_SUFFIX)] if dup_name.endswith(TMP_SUFFIX) else dup_name
    if base.endswith("DG"):
        base = base[:-2]
    return base + "V15"


def make_player_abp() -> None:
    if EAL.does_asset_exist(V15_ABP):
        tag = EAL.find_asset_data(V15_ABP).get_tag_value("ParentClass") or ""
        if "DigetherPlayerAnimInstance" in tag:
            log(f"플레이어 ABP 있음, 건너뜀: {V15_ABP}")
            return
        # retarget_ch_v15.py가 마네킹 ABP_Unarmed로 만든 기본 버전이다.
        # 커맨드렛에서는 에셋 삭제가 디스크에 반영되지 않아 직접 지우게 한다
        raise RuntimeError(f"마네킹 기반 {V15_ABP}가 있다. 에디터를 닫고 파일을 지운 뒤 다시 실행한다")

    # 이전 실행이 중간에 멈췄으면 임시 폴더의 결과에서 이어간다
    if not any(isinstance(EAL.load_asset(p), unreal.AnimBlueprint) for p in EAL.list_assets(TMP_DIR, recursive=False)):
        retarget_dwarf_abp()
    finish_player_abp()


def retarget_dwarf_abp() -> None:
    inputs = unreal.IKRetargetBatchOperationInputs()
    inputs.set_editor_property("assets_to_retarget", [EAL.find_asset_data(DWARF_ABP)])
    inputs.set_editor_property("source_mesh", load(DWARF_MESH))
    inputs.set_editor_property("target_mesh", load(V15_MESH))
    inputs.set_editor_property("ik_retarget_asset", make_dwarf_retargeter())
    inputs.set_editor_property("suffix", TMP_SUFFIX)
    inputs.set_editor_property("include_referenced_assets", True)
    inputs.set_editor_property("overwrite_existing_files", False)
    inputs.set_editor_property("use_source_path", False)
    inputs.set_editor_property("target_path", TMP_DIR)
    unreal.IKRetargetBatchOperation.run_batch_retarget(inputs)


def finish_player_abp() -> None:
    abp_tmp = None
    for path in EAL.list_assets(TMP_DIR, recursive=False):
        asset = EAL.load_asset(path)
        name = asset.get_name()
        if isinstance(asset, unreal.AnimBlueprint):
            abp_tmp = path.split(".")[0]
            continue
        target = f"{V15_ANIMS}/{v15_name_for(name)}"
        if EAL.does_asset_exist(target):
            ok = EAL.consolidate_assets(load(target), [asset])
            log(f"참조 합침 {name} -> {target} ({ok})")
        else:
            # 마네킹 V15 세트에 없는 애니메이션은 드워프를 거친 리타겟본을 그대로 쓴다
            EAL.rename_asset(path.split(".")[0], target)
            log(f"V15 세트에 없어 이동(드워프 경유 리타겟): {name} -> {target}")
    if abp_tmp is None:
        raise RuntimeError("ABP 리타겟 결과가 없다")
    if not EAL.rename_asset(abp_tmp, V15_ABP):
        raise RuntimeError(f"이동 실패: {abp_tmp} -> {V15_ABP}")

    abp = load(V15_ABP)
    unreal.BlueprintEditorLibrary.compile_blueprint(abp)
    EAL.save_loaded_asset(abp, only_if_is_dirty=False)
    if EAL.does_directory_exist(TMP_DIR) and not EAL.list_assets(TMP_DIR, recursive=True):
        EAL.delete_directory(TMP_DIR)
    log(f"플레이어 ABP 생성: {V15_ABP}")


def report_abp() -> None:
    data = EAL.find_asset_data(V15_ABP)
    reg = unreal.AssetRegistryHelpers.get_asset_registry()
    opts = unreal.AssetRegistryDependencyOptions(include_soft_package_references=True, include_hard_package_references=True)
    deps = [str(d) for d in reg.get_dependencies(data.package_name, opts) if str(d).startswith("/Game")]
    log(f"ABP 부모={data.get_tag_value('ParentClass')} 스켈레톤={load(V15_ABP).get_editor_property('target_skeleton').get_name()}")
    log(f"ABP 참조: {deps}")
    bad = [d for d in deps if "/Characters/Dwarf/" in d or TMP_SUFFIX in d]
    if bad:
        raise RuntimeError(f"ABP가 아직 드워프·임시 에셋을 참조한다: {bad}")


def check_shovel_montage() -> None:
    if not EAL.does_asset_exist(SHOVEL_MONTAGE):
        log("삽 몽타주 없음(create_shovel_attack_assets.py로 v15용 생성)")
        return
    montage = load(SHOVEL_MONTAGE)
    skel = montage.get_editor_property("skeleton")
    if skel == load(V15_MESH).skeleton:
        log("삽 몽타주가 이미 v15 스켈레톤, 유지")
        return
    length = montage.get_play_length()
    events = ANIMLIB.get_animation_notify_events(montage)
    windows = [(ANIMLIB.get_anim_notify_event_trigger_time(e), ANIMLIB.get_anim_notify_event_duration(e)) for e in events]
    default = (DEFAULT_HIT_START_RATIO * length, DEFAULT_HIT_LENGTH_RATIO * length)
    if any(abs(s - default[0]) > 0.01 or abs(d - default[1]) > 0.01 for s, d in windows):
        log(f"삽 몽타주 노티파이가 기본값과 달라(사람이 조정) 지우지 않음: {windows}, 직접 옮겨야 함")
        return
    # 커맨드렛 삭제는 디스크에 반영되지 않아 파일 삭제는 사람이 한다
    log(f"드워프용 삽 몽타주(노티파이 기본값 {windows}): 파일을 지우고 create_shovel_attack_assets.py로 v15용 재생성")


def update_player_bp() -> None:
    bp = load(PLAYER_BP)
    cdo = unreal.get_default_object(bp.generated_class())
    body = cdo.get_editor_property("mesh")
    mesh = load(V15_MESH)
    abp = load(V15_ABP)
    body.set_editor_property("skeletal_mesh_asset", mesh)
    body.set_editor_property("anim_class", abp.generated_class())
    # 뷰포트 표시용. 실행 중에는 ApplyPlayerStats가 같은 식으로 다시 계산한다
    bounds = mesh.get_imported_bounds()
    height = bounds.box_extent.z * 2.0
    scale = PLAYER_HEIGHT_CM / height
    bottom = bounds.origin.z - bounds.box_extent.z
    body.set_editor_property("relative_scale3d", unreal.Vector(scale, scale, scale))
    loc = body.get_editor_property("relative_location")
    body.set_editor_property("relative_location", unreal.Vector(loc.x, loc.y, -PLAYER_HEIGHT_CM * 0.5 - bottom * scale))
    unreal.BlueprintEditorLibrary.compile_blueprint(bp)
    if not EAL.save_loaded_asset(bp, only_if_is_dirty=False):
        raise RuntimeError(f"저장 실패(SVN 잠금 확인): {PLAYER_BP}")
    log(f"BP_DigatherPlayer: 메시={mesh.get_name()} 애님={abp.get_name()} 스케일={scale:.3f}")


def main() -> None:
    make_socket()
    make_player_abp()
    report_abp()
    check_shovel_montage()
    update_player_bp()
    log("완료")


main()
