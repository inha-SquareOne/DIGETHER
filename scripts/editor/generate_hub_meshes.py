"""로비용 신규 OBJ 원본 5개를 생성한다. 외부 패키지나 에디터가 필요 없다.

단위는 cm, Z-up이며 모든 면은 오른손 좌표계에서 외부를 향한 삼각형이다.
Unreal 도입 시 축 변환 설정은 도입 담당자가 확인한다. UV는 100cm 반복의
면별 평면 투영이고, 노멀은 면별 평면 노멀이다. 재질은 엔진에서 지정한다.

실행: python scripts/editor/generate_hub_meshes.py
기본 출력: DIGETHER/SourceArt/Hub. 기존 파일은 보존한다.
--overwrite는 아래에서 정한 5개 파일만 다시 생성한다.
"""

import argparse
from collections import Counter
import json
import math
from pathlib import Path


def subtract(a, b):
    return tuple(x - y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


class Mesh:
    def __init__(self, name):
        self.name = name
        self.vertices = []
        self.triangles = []
        self._vertex_indices = {}

    def vertex(self, position):
        # Shared seam vertices must have exactly the same indices for manifold QA.
        position = tuple(round(value, 8) for value in position)
        if position not in self._vertex_indices:
            self._vertex_indices[position] = len(self.vertices)
            self.vertices.append(position)
        return self._vertex_indices[position]

    def face(self, positions, outward):
        indices = [self.vertex(position) for position in positions]
        normal = cross(subtract(positions[1], positions[0]),
                       subtract(positions[2], positions[0]))
        if dot(normal, outward) < 0:
            indices.reverse()
        for index in range(1, len(indices) - 1):
            self.triangles.append((indices[0], indices[index], indices[index + 1]))

    def validate(self):
        edges = Counter()
        direction = Counter()
        volume = 0.0
        for triangle in self.triangles:
            a, b, c = (self.vertices[index] for index in triangle)
            normal = cross(subtract(b, a), subtract(c, a))
            if dot(normal, normal) < 1e-12:
                raise ValueError(f"{self.name}: degenerate triangle {triangle}")
            volume += dot(a, cross(b, c)) / 6.0
            for first, second in zip(triangle, triangle[1:] + triangle[:1]):
                edge = tuple(sorted((first, second)))
                edges[edge] += 1
                direction[edge] += 1 if first < second else -1
        if not all(count == 2 for count in edges.values()):
            raise ValueError(f"{self.name}: open or non-manifold edge")
        if any(direction.values()) or volume <= 0:
            raise ValueError(f"{self.name}: inconsistent or inward winding")
        if not all(math.isfinite(value) for point in self.vertices for value in point):
            raise ValueError(f"{self.name}: non-finite coordinate")
        return {
            "vertices": len(self.vertices),
            "triangles": len(self.triangles),
            "bounds_cm": [[min(point[axis] for point in self.vertices) for axis in range(3)],
                          [max(point[axis] for point in self.vertices) for axis in range(3)]],
            "closed_edges": len(edges),
            "degenerate_triangles": 0,
            "signed_volume_cm3": round(volume, 3),
        }

    def write_obj(self, path, overwrite):
        with path.open("w" if overwrite else "x", encoding="ascii", newline="\n") as output:
            output.write(f"# Generated by generate_hub_meshes.py; centimeters; Z-up\no {self.name}\ns off\n")
            for point in self.vertices:
                output.write("v " + " ".join(f"{value:.8f}" for value in point) + "\n")
            for triangle in self.triangles:
                a, b, c = (self.vertices[index] for index in triangle)
                normal = cross(subtract(b, a), subtract(c, a))
                dominant = max(range(3), key=lambda axis: abs(normal[axis]))
                axes = ((1, 2), (0, 2), (0, 1))[dominant]
                for point in (a, b, c):
                    output.write(f"vt {point[axes[0]] / 100:.8f} {point[axes[1]] / 100:.8f}\n")
            for triangle in self.triangles:
                a, b, c = (self.vertices[index] for index in triangle)
                normal = cross(subtract(b, a), subtract(c, a))
                length = math.sqrt(dot(normal, normal))
                output.write("vn " + " ".join(f"{value / length:.8f}" for value in normal) + "\n")
            for index, triangle in enumerate(self.triangles):
                output.write("f " + " ".join(
                    f"{vertex + 1}/{index * 3 + corner + 1}/{index + 1}"
                    for corner, vertex in enumerate(triangle)) + "\n")


def beveled_cube():
    mesh = Mesh("SM_HubBeveledCube")
    half, inset = 50, 46
    for axis in range(3):
        other = [value for value in range(3) if value != axis]
        for sign in (-1, 1):
            positions = []
            for first, second in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
                point = [0, 0, 0]
                point[axis] = sign * half
                point[other[0]], point[other[1]] = first * inset, second * inset
                positions.append(tuple(point))
            outward = [0, 0, 0]
            outward[axis] = sign
            mesh.face(positions, outward)
    for along in range(3):
        first, second = [axis for axis in range(3) if axis != along]
        for sign_a in (-1, 1):
            for sign_b in (-1, 1):
                positions = []
                for long, a, b in ((-inset, half, inset), (inset, half, inset),
                                   (inset, inset, half), (-inset, inset, half)):
                    point = [0, 0, 0]
                    point[along], point[first], point[second] = long, sign_a * a, sign_b * b
                    positions.append(tuple(point))
                outward = [0, 0, 0]
                outward[first], outward[second] = sign_a, sign_b
                mesh.face(positions, outward)
    for x in (-1, 1):
        for y in (-1, 1):
            for z in (-1, 1):
                mesh.face([(x * half, y * inset, z * inset),
                           (x * inset, y * half, z * inset),
                           (x * inset, y * inset, z * half)], (x, y, z))
    return mesh


def circle(radius, z, segments=48):
    return [(radius * math.cos(2 * math.pi * index / segments),
             radius * math.sin(2 * math.pi * index / segments), z)
            for index in range(segments)]


def half_disc_floor():
    mesh = Mesh("SM_HubHalfDiscFloor")
    top = [(450 * math.cos(math.pi * index / 32),
            450 * math.sin(math.pi * index / 32), 0) for index in range(33)]
    bottom = [(x, y, -20) for x, y, unused in top]
    mesh.face(top, (0, 0, 1))
    mesh.face(bottom, (0, 0, -1))
    for index in range(len(top)):
        following = (index + 1) % len(top)
        outward = (top[following][1] - top[index][1],
                   top[index][0] - top[following][0], 0)
        mesh.face([bottom[index], bottom[following], top[following], top[index]], outward)
    return mesh


def pool_rim():
    mesh = Mesh("SM_HubPoolRim")
    outer_bottom, outer_top = circle(220, 0), circle(220, 10)
    inner_bottom, inner_top = circle(200, 0), circle(200, 10)
    for index in range(48):
        following = (index + 1) % 48
        radial = outer_top[index][:2] + (0,)
        mesh.face([outer_top[index], outer_top[following], inner_top[following], inner_top[index]], (0, 0, 1))
        mesh.face([outer_bottom[index], outer_bottom[following], inner_bottom[following], inner_bottom[index]], (0, 0, -1))
        mesh.face([outer_bottom[index], outer_bottom[following], outer_top[following], outer_top[index]], radial)
        mesh.face([inner_bottom[index], inner_bottom[following], inner_top[following], inner_top[index]], tuple(-value for value in radial))
    return mesh


def dome():
    mesh = Mesh("SM_HubDome")
    # The visible underside keeps edge Z250 / apex Z278. Upper skin is 2cm above.
    for thickness, normal_z in ((0, -1), (2, 1)):
        rings = [circle(440 * fraction, 278 - 28 * fraction ** 2 + thickness, 16)
                 for fraction in (1, 2 / 3, 1 / 3)]
        for outer, inner in zip(rings, rings[1:]):
            for index in range(16):
                following = (index + 1) % 16
                mesh.face([outer[index], outer[following], inner[following], inner[index]], (0, 0, normal_z))
        for index in range(16):
            mesh.face([rings[-1][index], rings[-1][(index + 1) % 16], (0, 0, 278 + thickness)], (0, 0, normal_z))
    lower, upper = circle(440, 250, 16), circle(440, 252, 16)
    for index in range(16):
        following = (index + 1) % 16
        mesh.face([lower[index], lower[following], upper[following], upper[index]], lower[index][:2] + (0,))
    return mesh


def pool_disc():
    mesh = Mesh("SM_HubPoolDisc")
    lower, upper = circle(200, -3), circle(200, 0)
    for index in range(48):
        following = (index + 1) % 48
        mesh.face([upper[index], upper[following], (0, 0, 0)], (0, 0, 1))
        mesh.face([lower[index], lower[following], (0, 0, -3)], (0, 0, -1))
        mesh.face([lower[index], lower[following], upper[following], upper[index]], upper[index])
    return mesh


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path,
                        default=Path(__file__).resolve().parents[2] / "DIGETHER/SourceArt/Hub")
    parser.add_argument("--overwrite", action="store_true", help="Regenerate only the five known OBJ files")
    arguments = parser.parse_args()
    meshes = [builder() for builder in (beveled_cube, half_disc_floor, pool_rim, dome, pool_disc)]
    report = {mesh.name: mesh.validate() for mesh in meshes}
    paths = [arguments.output_dir / f"{mesh.name}.obj" for mesh in meshes]
    existing = [str(path) for path in paths if path.exists()]
    if existing and not arguments.overwrite:
        parser.error("Existing files preserved; use --overwrite explicitly: " + ", ".join(existing))
    arguments.output_dir.mkdir(parents=True, exist_ok=True)
    for mesh, path in zip(meshes, paths):
        mesh.write_obj(path, arguments.overwrite)
        report[mesh.name]["path"] = str(path.resolve())
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
